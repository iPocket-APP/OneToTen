import { expect, test } from '@playwright/test';
import { direction, languages, locales, pagePath } from '../src/browser/locale.ts';
import type { Messages } from '../src/browser/locales/zh-CN.ts';
import type { Session } from '../src/shared/room.ts';

test('all homepages and guides are localized and linked without JavaScript on a narrow screen', async ({ browser, baseURL }) => {
  const width = 320;
  const context = await browser.newContext({ baseURL, javaScriptEnabled: false, viewport: { width, height: 700 } });
  try {
    const page = await context.newPage();
    for (const locale of locales) {
      const { default: messages } = await import('../src/browser/locales/' + locale + '.ts') as { default: Messages };
      expect((await page.goto(pagePath(locale)))?.status()).toBe(200);
      await expect(page.locator('html')).toHaveAttribute('lang', locale);
      await expect(page.locator('html')).toHaveAttribute('dir', direction(locale));
      await expect(page).toHaveTitle(messages.text.homeMetaTitle);
      await expect(page.getByRole('heading', { level: 1 })).toHaveText(messages.text.homeTitle);
      await expect(page.getByRole('heading', { name: messages.text.agentGuide })).toBeVisible();
      await page.locator('.language-menu summary').click();
      await expect(page.locator('.language-options a')).toHaveCount(12);
      await expect(page.locator('.language-options a[aria-current="page"]')).toHaveText(languages[locale].name);
      expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(width);

      expect((await page.goto(pagePath(locale, 'guide')))?.status()).toBe(200);
      await expect(page).toHaveTitle(messages.text.guideMetaTitle);
      await expect(page.getByRole('heading', { level: 1 })).toHaveText(messages.text.guideTitle);
      await expect(page.locator('.site-header a.button')).toHaveAttribute('href', pagePath(locale));
      expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(width);
    }
  } finally { await context.close(); }
});

test('language changes retain form input, invitation, room, and a pending file transfer', async ({ page, browser, baseURL }) => {
  const receiver = await browser.newContext({ baseURL, locale: 'ja-JP', viewport: { width: 375, height: 812 } });
  const errors: string[] = [];
  page.on('pageerror', (error) => errors.push(error.message));
  try {
    await page.goto('/en/');
    await page.getByRole('button', { name: 'Join', exact: true }).click();
    await page.getByLabel('Invite link').fill('invalid');
    await page.getByRole('button', { name: 'Join room', exact: true }).click();
    await expect(page.getByRole('alert')).toHaveText('Enter the full invite link generated by this site.');
    await page.locator('.language-menu summary').click();
    await page.getByRole('link', { name: 'Français', exact: true }).click();
    await expect(page).toHaveURL(/\/fr\/$/);
    await expect(page.getByLabel('Lien d’invitation')).toHaveValue('invalid');
    await expect(page.getByRole('alert')).toHaveText('Saisissez le lien d’invitation complet généré par ce site.');
    await page.locator('.language-menu summary').click();
    await page.getByRole('link', { name: 'English', exact: true }).click();
    await page.getByRole('button', { name: 'Create', exact: true }).click();
    await page.getByLabel('Device name').fill('Sending Mac');
    await page.getByRole('button', { name: 'Create room', exact: true }).click();
    await expect(page.getByText('Room online', { exact: true })).toBeVisible();

    const invitePath = await page.evaluate(() => {
      const session = JSON.parse(sessionStorage.getItem('file-room:' + location.pathname.split('/').pop())!) as Session;
      return '/join/' + session.roomId + '#invite=' + session.invite?.secret;
    });
    const guest = await receiver.newPage();
    guest.on('pageerror', (error) => errors.push(error.message));
    await guest.goto(invitePath);
    await expect(guest).toHaveURL(/\/room\/[^/#]+$/);
    await expect(guest.getByRole('heading', { name: 'ルームに参加', level: 1 })).toBeVisible();
    await guest.getByLabel('端末名').fill('Receiving iPhone');
    await guest.locator('.language-menu summary').click();
    await guest.getByRole('button', { name: languages.ar.name, exact: true }).click();
    await expect(guest.locator('html')).toHaveAttribute('dir', 'rtl');
    await expect(guest.getByLabel('اسم الجهاز')).toHaveValue('Receiving iPhone');
    await guest.getByRole('button', { name: 'الانضمام إلى الغرفة', exact: true }).click();
    await expect(guest.getByText('الغرفة متصلة', { exact: true })).toBeVisible();

    const filename = 'localization-check.txt';
    await page.locator('input[type="file"]').setInputFiles({ name: filename, mimeType: 'text/plain', buffer: Buffer.from('One to Ten') });
    await page.getByRole('button', { name: 'Send to Receiving iPhone', exact: true }).click();
    const offer = guest.locator('[data-direction="receive"]');
    await expect(offer).toHaveAttribute('data-phase', 'incoming');
    await expect(guest.getByRole('heading', { name: 'طلب استلام ملف' })).toBeVisible();
    expect(await guest.evaluate(() => document.documentElement.scrollWidth)).toBe(375);
    const roomUrl = guest.url();
    await guest.locator('.language-menu summary').click();
    await guest.getByRole('button', { name: 'Français', exact: true }).click();
    await expect(guest.locator('html')).toHaveAttribute('dir', 'ltr');
    await expect(guest).toHaveURL(roomUrl);
    await expect(offer).toHaveAttribute('data-phase', 'incoming');
    await offer.getByRole('button', { name: 'Recevoir dans le navigateur', exact: true }).click();
    await expect(offer).toHaveAttribute('data-phase', 'stored');
    await expect(page.locator('[data-direction="send"]')).toHaveAttribute('data-phase', 'stored');
    await expect(guest.getByText('Fichier reçu', { exact: true })).toBeVisible();

    await guest.reload();
    await expect(guest.getByText('Salon en ligne', { exact: true })).toBeVisible();
    expect((await guest.goto('/missing-language-check'))?.status()).toBe(404);
    await expect(guest.getByRole('heading', { name: 'Page introuvable', level: 1 })).toBeVisible();
    await expect(guest.getByRole('link', { name: 'Retour à One to Ten' })).toHaveAttribute('href', '/fr/');
    expect(errors).toEqual([]);
  } finally { await receiver.close(); }
});
